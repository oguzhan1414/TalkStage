"""
Makes the pronunciation clips of the word lists (Kütüphane with antonyms, Telaffuz) with Cartesia, in Mivo's voice,
as small mono MP3s bundled in the app, so a word plays at once, offline and at no cost.

Words come from backend/app/tools/prewarm_words.json. Each clip is mobile/assets/audio/words/<key>.mp3 where key is
pathAudioKey(text) (mobile/src/lib/pathAudioKey.ts, FNV-1a), the same naming as the lesson clips. Clips that already
exist are skipped, so a rerun only pays for new words. At the end mobile/src/assets/wordAudio.ts (the registry the
app looks clips up in) is rewritten.

Usage (from backend/): python scripts/generate_word_audio.py [--limit N] [--words app/tools/room_words.json]
Needs CARTESIA_API_KEY and CARTESIA_VOICE_ID in backend/.env and ffmpeg on PATH.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import time
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WORDS = ROOT / "backend" / "app" / "tools" / "prewarm_words.json"
OUT = ROOT / "mobile" / "assets" / "audio" / "words"
REGISTRY = ROOT / "mobile" / "src" / "assets" / "wordAudio.ts"
MODEL = "sonic-3.6"
URL = "https://api.cartesia.ai/tts/bytes"
VERSION = "2026-08-14"


def load_env() -> dict[str, str]:
    env = {}
    for line in (ROOT / "backend" / ".env").read_text(encoding="utf-8").splitlines():
        if "=" in line and not line.strip().startswith("#"):
            k, v = line.split("=", 1)
            env[k.strip()] = v.strip().strip('"').strip("'")
    return env


def audio_text(text: str) -> str:
    """Same as pathAudioText in the app."""
    return re.sub(r"[.!?…]+$", "", re.sub(r"\s+", " ", text.strip())).strip()


def audio_key(text: str) -> str:
    """Same as pathAudioKey in the app: FNV-1a 32 bit over UTF-16 code units, 8 hex digits."""
    s = audio_text(text)
    h = 0x811C9DC5
    data = s.encode("utf-16-le")
    for i in range(0, len(data), 2):
        h ^= data[i] | (data[i + 1] << 8)
        h = (h * 0x01000193) & 0xFFFFFFFF
    return f"{h:08x}"


def synth(api_key: str, voice: str, text: str) -> bytes:
    body = {
        "model_id": MODEL,
        "transcript": text,
        "voice": voice,
        "language": "en",
        "output_format": {"container": "wav", "encoding": "pcm_s16le", "sample_rate": 24000},
    }
    req = urllib.request.Request(
        URL,
        data=json.dumps(body).encode(),
        headers={"Authorization": f"Bearer {api_key}", "Cartesia-Version": VERSION, "Content-Type": "application/json"},
        method="POST",
    )
    for attempt in range(5):
        try:
            return urllib.request.urlopen(req, timeout=60).read()
        except urllib.error.HTTPError as e:
            if e.code in (429, 500, 502, 503) and attempt < 4:
                time.sleep(2 * (attempt + 1))
                continue
            raise RuntimeError(f"HTTP {e.code}: {e.read()[:300]!r}") from e
        except urllib.error.URLError:
            if attempt < 4:
                time.sleep(2 * (attempt + 1))
                continue
            raise
    raise RuntimeError("unreachable")


def squeeze(wav: bytes, out: Path) -> None:
    """Mono, 24 kHz, 32 kbit/s MP3, like the lesson clips."""
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-i", "pipe:0", "-ac", "1", "-ar", "24000", "-b:a", "32k", str(out)],
        input=wav,
        check=True,
    )


def write_registry() -> int:
    keys = sorted(p.stem for p in OUT.glob("*.mp3"))
    lines = [
        "/**",
        " * Pre-made pronunciation clips of the word lists (Kütüphane, Telaffuz), Cartesia in Mivo's voice, keyed by",
        " * pathAudioKey(text). Generated by backend/scripts/generate_word_audio.py; do not edit by hand.",
        " */",
        "export const WORD_AUDIO: Record<string, number> = {",
    ]
    lines += [f"  '{k}': require('../../assets/audio/words/{k}.mp3')," for k in keys]
    lines += ["};", ""]
    REGISTRY.write_text("\n".join(lines), encoding="utf-8")
    return len(keys)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--words", default=str(WORDS), help="JSON list of texts (default: the Kütüphane + Telaffuz words)")
    args = ap.parse_args()
    env = load_env()
    api_key, voice = env["CARTESIA_API_KEY"], env["CARTESIA_VOICE_ID"]
    OUT.mkdir(parents=True, exist_ok=True)

    words = json.loads(Path(args.words).read_text(encoding="utf-8"))
    seen: set[str] = set()
    todo: list[tuple[str, str]] = []
    for w in words:
        k = audio_key(w)
        if k in seen:
            continue
        seen.add(k)
        if not (OUT / f"{k}.mp3").exists():
            todo.append((k, audio_text(w)))
    if args.limit:
        todo = todo[: args.limit]
    print(f"{len(seen)} clips, {len(todo)} to make ({sum(len(t) for _, t in todo)} characters)")

    made = failed = 0
    with ThreadPoolExecutor(max_workers=3) as pool:
        futures = {pool.submit(synth, api_key, voice, text): (k, text) for k, text in todo}
        for fut in as_completed(futures):
            k, text = futures[fut]
            try:
                squeeze(fut.result(), OUT / f"{k}.mp3")
                made += 1
            except Exception as exc:  # a rerun fills the gaps
                failed += 1
                print(f"  failed {text!r}: {exc}")
            if (made + failed) % 100 == 0:
                print(f"  {made} made, {failed} failed")
    n = write_registry()
    print(f"finished: {made} made, {failed} failed; registry lists {n} clips")


if __name__ == "__main__":
    main()
