/** File-name key of a word: "Wake up" → wake_up, "café" → cafe. */
export function wordKey(en: string): string {
  return en
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\s+/g, '_');
}

/** The picture of a word, if it has one. */
export function wordImage(en: string): number | undefined {
  return WORD_IMAGES[wordKey(en)];
}
