/**
 * Rebuilds src/assets/pathImages.ts (the step covers) from the pictures on disk:
 *   assets/images/path/*.webp                  (A1 and A2: a1_e01, a2_w3 …)
 *   assets/images/path/<level>/covers/*.webp   (one folder per level from B1 on: b1_e01, b1_w1 …)
 * Keys are the file names without .webp: `<level>_eNN` for an episode, `<level>_wN` for the word step of unit N.
 * Run from mobile/: node scripts/gen-path-images.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const pathDir = path.join(root, 'assets/images/path');
const dirs = [pathDir];
for (const level of fs.readdirSync(pathDir).sort()) {
  const covers = path.join(pathDir, level, 'covers');
  if (fs.existsSync(covers) && fs.statSync(covers).isDirectory()) dirs.push(covers);
}

const entries = new Map();
for (const dir of dirs) {
  for (const file of fs.readdirSync(dir).filter((f) => /^[a-c][12]_(e\d\d|w\d)\.webp$/.test(f))) {
    const key = file.slice(0, -5);
    if (entries.has(key)) throw new Error(`"${key}" has two pictures: ${entries.get(key)} and ${path.join(dir, file)}`);
    entries.set(key, path.join(dir, file));
  }
}

const rel = (p) => path.relative(path.join(root, 'src/assets'), p).split(path.sep).join('/');
const lines = [...entries.keys()].sort().map((k) => `  ${k}: require('${rel(entries.get(k))}'),`);

const out = `/**
 * Cover pictures of the learning path (prompts: docs/<level>_gorsel_promptlari.md), keyed \`a1_e01\` (episode) and
 * \`a1_w1\` (word step of unit 1). Generated by scripts/gen-path-images.js from assets/images/path and
 * assets/images/path/<level>/covers; do not edit by hand. Steps without a picture fall back to Mivo.
 */
export const PATH_IMAGES: Record<string, number> = {
${lines.join('\n')}
};
`;
fs.writeFileSync(path.join(root, 'src/assets/pathImages.ts'), out);
console.log(`${entries.size} covers → src/assets/pathImages.ts (${dirs.length} folders)`);
