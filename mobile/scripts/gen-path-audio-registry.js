/**
 * Writes src/assets/pathAudio.ts: one require() per clip in assets/audio/path (Metro needs static requires).
 * Run after backend/scripts/generate_path_audio.py: node scripts/gen-path-audio-registry.js
 */
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'assets', 'audio', 'path');
const out = path.join(__dirname, '..', 'src', 'assets', 'pathAudio.ts');
const keys = fs.existsSync(dir)
  ? fs
      .readdirSync(dir)
      .filter((f) => f.endsWith('.mp3'))
      .map((f) => f.slice(0, -4))
      .sort()
  : [];

const lines = [
  '/**',
  ' * Pre-made voice clips of the learning path, keyed by pathAudioKey(text) (lib/pathAudioKey.ts).',
  ' * Generated by scripts/gen-path-audio-registry.js; do not edit by hand.',
  ' */',
  'export const PATH_AUDIO: Record<string, number> = {',
  ...keys.map((k) => `  '${k}': require('../../assets/audio/path/${k}.mp3'),`),
  '};',
  '',
];
fs.writeFileSync(out, lines.join('\n'));
console.log(`${keys.length} clips → ${path.relative(process.cwd(), out)}`);
